const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { Conversion } = require('./conversion');

test('conversion validates options, isolates output, and selects the finished package', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'conversion-test-'));
  t.after(() => fs.rmSync(root, {recursive:true,force:true}));
  const iso = path.join(root, 'game with spaces.iso'); fs.writeFileSync(iso, 'untouched');
  const fake = path.join(root, 'converter');
  fs.writeFileSync(fake, `#!${process.execPath}\nconst fs=require('fs'),path=require('path');const args=process.argv.slice(2);const out=args[args.indexOf('--out')+1];fs.writeFileSync(path.join(out,'args.json'),JSON.stringify(args));fs.writeFileSync(path.join(out,'game.pkg'),Buffer.from('7f434e54010203','hex'));console.log('30/30 checks OK');`, {mode:0o700});
  let selected;
  const c = new Conversion({executable:fake,outputRoot:path.join(root,'out'),pickFile:async()=>iso,onComplete:p=>selected=p});
  await assert.rejects(c.start(), /Selecione/);
  await c.select();
  await assert.rejects(c.start({emulator:'bad'}),/inválida/);
  const title = 'Title $(touch NO) `noop`';
  await c.start({title,emulator:'Rogue v1',resolution:'1x1'});
  await assert.rejects(c.start(), /andamento/);
  await c.done;
  assert.equal(c.state().status,'success');
  assert.equal(selected,c.state().output);
  const args=JSON.parse(fs.readFileSync(path.join(path.dirname(selected),'args.json')));
  assert.equal(args[0],iso);assert.equal(args.at(-1),title);
  assert.equal(fs.readFileSync(iso,'utf8'),'untouched');
  const first=selected;await c.start();await c.done;
  assert.notEqual(first,selected);assert.ok(fs.existsSync(first));
  const calls=[];
  const again=new Conversion({outputRoot:path.join(root,'out'),open:async(...args)=>calls.push(args)});
  assert.equal(again.state().lastOutput,'');
  assert.equal(fs.existsSync(path.join(root,'out','last-result.json')),false);
  assert.equal(await c.discard(path.join(root,'iso-outside.pkg')),false);
  assert.equal(await c.discard(selected),true);
  assert.equal(fs.existsSync(path.dirname(selected)),false);assert.ok(fs.existsSync(first));
  assert.equal(c.state().lastOutput,'');assert.equal(fs.readFileSync(iso,'utf8'),'untouched');
  await c.purge();assert.equal(fs.existsSync(path.join(root,'out')),false);assert.equal(fs.readFileSync(iso,'utf8'),'untouched');
});

test('failure and cancellation never select incomplete output or delete the ISO', async t => {
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'conversion-fail-'));
  t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
  const iso=path.join(root,'game.iso');fs.writeFileSync(iso,'source');
  const fake=path.join(root,'converter');
  fs.writeFileSync(fake,`#!${process.execPath}\nsetTimeout(()=>process.exit(2),100);`,{mode:0o700});
  let selected=false;
  const c=new Conversion({executable:fake,outputRoot:path.join(root,'out'),pickFile:async()=>iso,onComplete:()=>selected=true});
  await c.select();await c.start();await c.done;
  assert.equal(c.state().status,'error');assert.equal(selected,false);
  fs.writeFileSync(fake,`#!${process.execPath}\nsetInterval(()=>{},1000);`,{mode:0o700});
  await c.start();
  for(let i=0;i<100&&!c.child;i++)await new Promise(r=>setTimeout(r,10));
  c.cancel();await c.done;
  assert.equal(c.state().status,'cancelled');assert.equal(selected,false);assert.equal(fs.readFileSync(iso,'utf8'),'source');
  assert.deepEqual(fs.readdirSync(path.join(root,'out')),[]);
});

test('cover is resized to square PNG, passed to the converter and removable', {skip:process.platform!=='darwin'}, async t => {
  const {promisify}=require('node:util');
  const run=promisify(require('node:child_process').execFile);
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'cover-test-'));
  t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
  const image=path.join(root,'portrait.png');
  await run('/usr/bin/sips',['-s','format','png','-z','24','12',path.join(__dirname,'packaging/app/AppIcon.icns'),'--out',image]);
  const original=fs.readFileSync(image);
  const iso=path.join(root,'game.iso');fs.writeFileSync(iso,'iso');
  const tool=path.join(root,'converter');
  fs.writeFileSync(tool,`#!${process.execPath}\nconst fs=require('fs'),path=require('path');const a=process.argv.slice(2),o=a[a.indexOf('--out')+1];fs.copyFileSync(a[a.indexOf('--icon')+1],path.join(o,'cover.png'));fs.writeFileSync(path.join(o,'game.pkg'),Buffer.from('7f434e54','hex'));`,{mode:0o700});
  let chosen=image;
  const c=new Conversion({executable:tool,outputRoot:path.join(root,'out'),pickFile:async()=>iso,pickCoverFile:async()=>chosen});
  await c.selectCover();
  assert.equal(c.state().coverSelected,true);
  const info=(await run('/usr/bin/sips',['-g','pixelWidth','-g','pixelHeight','-g','format',c.cover])).stdout;
  assert.match(info,/pixelWidth: 512/);assert.match(info,/pixelHeight: 512/);assert.match(info,/format: png/);
  assert.deepEqual(fs.readFileSync(image),original);
  const prior=c.cover;chosen=iso;await assert.rejects(c.selectCover(),/PNG ou JPG/);assert.equal(c.cover,prior);
  await c.select();await c.start();await c.done;
  assert.equal(c.state().status,'success');
  assert.ok(fs.existsSync(path.join(path.dirname(c.state().output),'cover.png')));
  c.clearCover();assert.equal(c.state().coverSelected,false);
});


test('missing PS2 boot serial explains unsupported images and preserves the source and previous result', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'conversion-serial-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const iso = path.join(root, 'homebrew.iso'); fs.writeFileSync(iso, 'BOOT2 = cdrom0:\\SNES_EMU.ELF;1');
  const original = fs.readFileSync(iso);
  const out = path.join(root, 'out'); fs.mkdirSync(out);
  const previous = path.join(out, 'previous.pkg'); fs.writeFileSync(previous, Buffer.from('7f434e54', 'hex'));
  const fake = path.join(root, 'converter');
  fs.writeFileSync(fake, `#!${process.execPath}\nconsole.error('ERROR: could not detect a PS2 boot serial (e.g. SLUS_209.32) in the ISO');process.exit(1);`, { mode: 0o700 });
  let selected = false;
  const c = new Conversion({ executable: fake, outputRoot: out, onComplete: () => { selected = true; } });
  await c.useIso(iso); await c.start(); await c.done;
  assert.equal(c.state().status, 'error');
  assert.match(c.state().error, /identificador de inicialização/);
  assert.match(c.state().error, /SNES\/retrôs ainda não está integrado/);
  assert.match(c.state().error, /não indica uma ISO corrompida/);
  assert.ok(c.state().log.some(line => line.includes('could not detect a PS2 boot serial')));
  assert.equal(selected, false); assert.equal(c.state().output, '');
  assert.equal(c.state().lastOutput, ''); assert.ok(fs.existsSync(previous));
  assert.deepEqual(fs.readFileSync(iso), original);
  assert.deepEqual(fs.readdirSync(out).sort(), ['previous.pkg']);
});
