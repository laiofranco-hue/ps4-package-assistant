const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const {spawn}=require('node:child_process');
const {Library}=require('./library');
test('library API selects files without converting or sending, rejects unsupported platforms and cross-origin mutations',async t=>{
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'library-api-'));
  const games=path.join(root,'games');fs.mkdirSync(games);
  fs.writeFileSync(path.join(games,'ps2.iso'),'BOOT2 = cdrom0:\\SLPM_663.74');
  fs.writeFileSync(path.join(games,'unknown.iso'),'unknown');
  fs.writeFileSync(path.join(games,'ps1.iso'),'BOOT = cdrom:\\SLUS_000.00');
  fs.writeFileSync(path.join(games,'retro.sfc'),'ROM');
  fs.writeFileSync(path.join(games,'valid.pkg'),Buffer.from('7f434e540001','hex'));
  fs.writeFileSync(path.join(games,'invalid.pkg'),'bad');
  const seed=new Library({dataDir:path.join(root,'data')});await seed.add([games],'folder');await seed.done;
  const child=spawn(process.execPath,['server.js'],{env:{...process.env,UI_PORT:'14175',FILE_PORT:'18082',LIBRARY_DATA_DIR:seed.dataDir}});
  t.after(async()=>{child.kill();await new Promise(r=>child.once('exit',r));fs.rmSync(root,{recursive:true,force:true})});
  await new Promise((resolve,reject)=>{let text='';child.stdout.on('data',c=>{text+=c;if(text.includes('Servidor de pacotes'))resolve()});child.once('error',reject);child.once('exit',code=>reject(new Error('server exited '+code)))});
  const base='http://127.0.0.1:14175';
  const get=async(route)=>await(await fetch(base+route)).json();
  const post=async(route,body={},headers={})=>{const r=await fetch(base+route,{method:'POST',headers:{'Content-Type':'application/json',...headers},body:JSON.stringify(body)});return {status:r.status,data:await r.json()}};
  const state=await get('/api/library');assert.equal(state.items.length,6);
  const id=name=>state.items.find(x=>path.basename(x.path)===name).id;
  assert.equal((await post('/api/library/use',{id:id('valid.pkg')})).status,200);
  assert.match((await get('/api/state')).selectedFile,/valid.pkg$/);
  assert.equal((await post('/api/library/use',{id:id('ps2.iso')})).status,200);
  assert.equal((await get('/api/state')).selectedFile,'');assert.match((await get('/api/conversion')).iso,/ps2.iso$/);
  assert.equal((await get('/api/conversion')).status,'idle');
  for(const name of ['retro.sfc','ps1.iso','invalid.pkg'])assert.equal((await post('/api/library/use',{id:id(name)})).status,400,name);
  assert.equal((await post('/api/library/use',{id:id('unknown.iso')})).status,400);
  assert.equal((await post('/api/library/use',{id:id('unknown.iso'),confirmPS2:true})).status,200);
  assert.equal((await post('/api/library/sync',{}, {Origin:'https://example.invalid'})).status,403);
  fs.appendFileSync(path.join(games,'valid.pkg'),'changed');assert.equal((await post('/api/library/use',{id:id('valid.pkg')})).status,400);
  assert.equal((await post('/api/library/sync')).status,202);
  let synced;for(let i=0;i<100;i++){synced=await get('/api/library');if(!synced.syncing)break;await new Promise(r=>setTimeout(r,10))}
  assert.equal(synced.error,'');assert.equal(synced.syncing,false);
  assert.equal((await post('/api/library/use',{id:id('valid.pkg')})).status,200);
  assert.ok(fs.existsSync(path.join(games,'valid.pkg')));
});
